// Ранжирует заголовки-кандидаты от самого многообещающего (живая, конкретная
// история) до наименее (сухая "статья-зонтик" про целую страну/эпоху/процесс).
// Используется перед тем, как тратить запросы на загрузку полного текста —
// так реже долетаем до статей вида "Узбекистан" или "Индустриализация СССР".
async function pickMostInteresting(candidates, { regionName, themeName } = {}) {
  if (!candidates || candidates.length <= 1) return candidates || [];

  const apiKey = process.env.GEMINI_API_KEY;

  const systemPrompt = `Ты — редактор популярного Telegram-канала об истории.

Тебе дают список заголовков-кандидатов на сегодняшний пост. Тема выпуска:
"${themeName}". Регион: "${regionName}".

Расставь заголовки по убыванию того, насколько живой и конкретный пост
из них получится.

СТАВЬ В КОНЕЦ списка заголовки, которые почти наверняка дадут сухой
учебниковый текст: названия целых государств, республик, стран, народов,
эпох, идеологий, экономических процессов ("Индустриализация",
"Коллективизация", "Гражданская война", "Узбекистан", "Депрессия (экономика)"),
официальных институтов, договоров, административных реформ.

СОВСЕМ В КОНЕЦ — заголовки, которые вообще не про историю/географию/культуру
прошлого: современные фильмы, сериалы, песни, альбомы, певцы, игры, аэропорты,
спортивные клубы, страницы значений.

СТАВЬ В НАЧАЛО списка заголовки, которые звучат как конкретная история:
предмет, находка, здание, человек, случай, произведение, необычное явление,
скандал, техническая деталь — то, что можно живо представить и рассказать
за 2-3 предложения.

Ответь СТРОГО списком заголовков через перенос строки, от самого
многообещающего к наименее, без номеров, пояснений и изменений формулировок.
Верни ВСЕ заголовки из списка, ничего не добавляя.`;

  const text = await callGemini(apiKey, {
    system_instruction: { parts: [{ text: systemPrompt }] },
    generationConfig: { temperature: 0.3 },
    contents: [{ role: "user", parts: [{ text: candidates.join("\n") }] }],
  });

  if (!text) return candidates;

  const ranked = text
    .split("\n")
    .map((s) => s.trim())
    .filter((s) => candidates.includes(s));

  // подстраховка: если модель что-то упустила, дописываем оставшихся
  // кандидатов в конец в исходном порядке, а не теряем их
  const rankedSet = new Set(ranked);
  const missing = candidates.filter((c) => !rankedSet.has(c));
  return [...ranked, ...missing];
}

// Исторический пост по статье Wikipedia, в конце которого — отсылка к
