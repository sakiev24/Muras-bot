const { fetchWithRetry } = require("./http");

const GEMINI_API_URL =
  "https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent";

function callGemini(apiKey, body) {
  return fetchWithRetry(
    `${GEMINI_API_URL}?key=${apiKey}`,
    {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(body),
    },
    { context: "Gemini", timeoutMs: 45000 }
  );
}

async function rewriteAsFact({ articleText, articleTitle, regionName, themeName, themeLens }) {
  const apiKey = process.env.GEMINI_API_KEY;

  // Ограничиваем длину исходного текста, чтобы не тратить лишние токены
  const trimmedText = articleText.slice(0, 6000);

  const systemPrompt = `Ты пишешь короткие подписи к историческим постам для Telegram — 
в стиле лаконичных подписей под фото в познавательных пабликах, а не статей.

Тебе дают текст статьи из Wikipedia. Тема выпуска: "${themeName}" (${themeLens}).
Регион: ${regionName}.

ФОРМАТ СТРОГО ТАКОЙ (два блока, разделённые пустой строкой):

[Блок 1 — одно предложение]: конкретное, интересное утверждение о том, ЧТО это 
за находка/событие/явление и когда/где. Без вводных фраз, сразу суть.

[пустая строка]

[Блок 2 — одно-два предложения]: самая конкретная и неожиданная деталь из статьи 
(цифра, имя, факт), которая заставляет удивиться. Не общее рассуждение, 
а конкретика.

ПРИМЕР нужного стиля (не копируй содержание, только формат):
"Древнеримская мозаика с лицами атлетов из IV века нашей эры.

В банях Каракаллы, панель включала более 100 борцов, боксеров и других 
атлетов с местных соревнований."

Что важно:
- ВСЕГО 2-3 предложения на весь пост. Не больше. Это не абзац, а короткая подпись.
- Делай акцент на теме "${themeName}", если в статье есть на что опереться.
- НЕ выдумывай факты, которых нет в исходном тексте.
- НЕ копируй предложения дословно — формулируй заново.

ЗАПРЕЩЁННЫЙ ТИП ФАКТА — избегай любой ценой:
- Даты, длительности, вычисленные интервалы времени как главный смысл факта 
  (например: "X просуществовал 54 года 8 месяцев", "с 1929 по 1941 год..."). 
  Такие "факты" — это просто арифметика, а не что-то интересное. Дата может 
  быть фоном, но НЕ должна быть сутью предложения.
- Общие абстрактные утверждения про "государство", "систему", "эпоху" без 
  конкретного физического объекта, человека, числа предметов или детали, 
  которую можно представить.

ЧТО ИСКАТЬ ВМЕСТО ЭТОГО — конкретный артефакт, деталь или образ, который 
можно представить или увидеть: конкретный предмет, находка, здание, 
изображение, число людей/вещей, странная деталь быта, необычное правило 
или парадокс. Если статья не даёт такой конкретики — лучше взять другую 
деталь из текста, но не заменять её датами/сроками.

- Никакого канцелярита ("колоссальные перемены", "определил облик", 
  "грандиозные испытания" и подобных штампов).
- Максимум 1 эмодзи, и то не обязательно.
- Ответь только текстом поста в этом формате, без предисловий от себя.`;

  const response = await callGemini(apiKey, {
    system_instruction: {
      parts: [{ text: systemPrompt }],
    },
    contents: [
      {
        role: "user",
        parts: [{ text: `Статья "${articleTitle}":\n\n${trimmedText}` }],
      },
    ],
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Gemini API error: ${response.status} ${errText}`);
  }

  const data = await response.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
  return text ? text.trim() : null;
}

async function generatePopCultureFact({ topicTitle, topicNote, verified }) {
  const apiKey = process.env.GEMINI_API_KEY;

  const verifiedInstruction = verified
    ? `Это задокументированный факт — пиши уверенно, как установленную информацию.`
    : `Это распространённая интерпретация/толкование, а НЕ официально подтверждённый факт. 
Обязательно формулируй с оговоркой: "многие видят в этом...", "по одной из трактовок...", 
"считается, что..." — НЕ подавай это как безусловную истину.`;

  const systemPrompt = `Ты пишешь короткие посты для Telegram-канала об истории, которые 
иногда связывают исторические/культурные явления с современной поп-культурой 
(фильмы, игры, музыка).

Тема поста: "${topicTitle}" (${topicNote}).

${verifiedInstruction}

ФОРМАТ СТРОГО ТАКОЙ (два блока, разделённые пустой строкой), 2-3 предложения всего:

[Блок 1]: одно предложение — конкретная связь между произведением и реальным 
историческим/культурным явлением.

[пустая строка]

[Блок 2]: одно-два предложения — конкретная деталь, объясняющая эту связь.

Что важно:
- Никакого канцелярита и общих фраз.
- Пиши конкретно, с именами/деталями, а не абстрактно.
- НЕ выдумывай дополнительных фактов сверх того, что реально известно по теме — 
  если сомневаешься в детали, лучше не включать её.
- Максимум 1 эмодзи.
- Ответь только текстом поста, без предисловий от себя.`;

  const response = await callGemini(apiKey, {
    system_instruction: { parts: [{ text: systemPrompt }] },
    contents: [
      {
        role: "user",
        parts: [{ text: `Напиши пост про "${topicTitle}".` }],
      },
    ],
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Gemini API error: ${response.status} ${errText}`);
  }

  const data = await response.json();
  const text = data.candidates?.[0]?.content?.parts?.[0]?.text;
  return text ? text.trim() : null;
}

module.exports = { rewriteAsFact, generatePopCultureFact };